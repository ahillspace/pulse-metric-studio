/** Build a stable cache key from session boundary + datasource LUID. No secrets. */
function fieldCatalogCacheKey(session: TableauSession, luid: string): string {
  const server = normalizeServerUrl(session.serverUrl);
  return `${server}|${session.siteId}|${session.userId}|${luid}`;
}

/**
 * Field discovery for the metric builder.
 *
 * Primary path: VizQL Data Service (VDS), which reads the published model
 * directly and is available immediately after publish (no search-index lag).
 * Includes calculation formulas, columnClass, default aggregation, logical
 * tables/relationships and parameters.
 *
 * Fallback: Metadata API GraphQL when VDS is unavailable on the pod (some
 * Tableau instances do not have VDS enabled). See metadata-fallback.ts — it
 * carries the dependency-graph taint traversal that VDS makes unnecessary here.
 *
 * On the VDS path, classification is driven natively off `read-metadata`:
 * - `columnClass === 'TABLE_CALCULATION'` -> excluded. VDS flags this even when
 *   a calc merely *references* a table calc, so the nested case is handled
 *   without any formula-syntax scanning.
 * - `columnClass === 'BIN'` -> excluded (bin).
 * - hidden / internal -> excluded.
 * - `defaultAggregation` AGG/USER -> requiresUserAgg (publish with
 *   AGGREGATION_USER); a bare aggregation (SUM/YEAR/…) means VDS already
 *   aggregates it for us.
 *
 * The metadata fallback precomputes the same decisions and hands them over via
 * `exclusionHint` / `requiresUserAggHint` so `classifyField` stays the single
 * place that builds a CatalogField.
 */

export interface VdsField {
  name?: string;
  caption?: string | null;
  dataType?: string;
  fieldType?: string;
  physicalType?: string | null;
  columnClass?: string;
  defaultAggregation?: string | null;
  formula?: string | null;
  dataCategory?: string;
  role?: string;
  isHidden?: boolean;
  isInternal?: boolean;
  isAutoGenerated?: boolean;
  hasUserReference?: boolean;
  logicalTableId?: string | null;
  provenance?: FieldProvenance;
  /**
   * Precomputed exclusion decision from a source that classifies fields itself
   * (the Metadata API fallback). `undefined` = classify natively from VDS
   * fields; `null` = explicitly allowed; a reason = excluded for that reason.
   */
  exclusionHint?: FieldExclusionReason | null;
  /** Precomputed requiresUserAgg decision (Metadata API fallback). */
  requiresUserAggHint?: boolean;
}

/**
 * Actual `read-metadata` row shape (verified live 2026-08):
 * {fieldName, fieldCaption, dataType, fieldRole, fieldType, defaultAggregation,
 *  columnClass, logicalTableId, formula?}
 */
interface VdsReadMetadataResponse {
  data?: Array<{
    fieldName?: string;
    fieldCaption?: string;
    dataType?: string;
    fieldType?: string;
    fieldRole?: string;
    defaultAggregation?: string | null;
    columnClass?: string;
    formula?: string | null;
    logicalTableId?: string | null;
    isHidden?: boolean;
    isInternal?: boolean;
  }>;
  extraData?: {
    parameters?: Array<{ parameterCaption?: string; parameterName?: string; parameterType?: string; dataType?: string }>;
  };
}

interface VdsModel {
  datasourceDescription?: string;
  datasourceModel?: {
    logicalTables?: Array<{ logicalTableId: string; caption?: string }>;
    logicalTableRelationships?: unknown[];
  };
  fieldGroups?: Array<{ logicalTableId?: string | null; fields?: VdsField[] }>;
  parameters?: Array<{ name?: string; parameterType?: string; dataType?: string }>;
  fieldProvenance?: FieldProvenance;
}

interface RawDatasource {
  luid: string;
  name: string;
}

export interface FieldsCacheEntry {
  catalog: DatasourceCatalog;
  fetchedAt: number;
}

const CACHE_TTL_MS = 5 * 60_000;
const SUSPICIOUS_ZERO_TIME_CACHE_TTL_MS = 15_000;
const cache = new Map<string, FieldsCacheEntry>();

/** Authoring can use an already loaded catalog; publishing still requests fresh validation. */
export function getLoadedFieldCatalog(session: TableauSession, luid: string): DatasourceCatalog | undefined {
  return cache.get(fieldCatalogCacheKey(session, luid))?.catalog;
}

export function invalidateFieldsCache(luid?: string): void {
  if (luid) {
    for (const key of cache.keys()) {
      if (key.endsWith(`|${luid}`)) cache.delete(key);
    }
  } else {
    cache.clear();
  }
}

export interface ListedDatasource extends RawDatasource {
  projectName: string;
}

export async function listDatasources(session: TableauSession): Promise<ListedDatasource[]> {
  const out: ListedDatasource[] = [];
  let pageNumber = 1;
  const pageSize = 1000;
  for (;;) {
    // Site-scoped path — some pods reject the token-scoped form for this resource.
    let data: any;
    try {
      data = await getJson<any>(
        session,
        apiPath(session, `/sites/${encodeURIComponent(session.siteId)}/datasources?pageSize=${pageSize}&pageNumber=${pageNumber}`),
      );
    } catch (e) {
      // Some pods return 400006 instead of an empty page past the end.
      if (isPastEndError(e)) break;
      throw e;
    }
    const raw = data?.datasources?.datasource ?? data?.datasources;
    const ds = Array.isArray(raw) ? (raw as any[]) : [];
    for (const d of ds) {
      // Modern pods return only `id` (which IS the LUID); older shapes had both.
      // Ledger A9 intent preserved by validating UUID shape rather than key name.
      const candidate = d.luid ?? d.id;
      if (!candidate || !isLuidShape(String(candidate))) continue;
      out.push({
        luid: String(candidate),
        name: String(d.name ?? 'Unnamed'),
        projectName: String(d.project?.name ?? ''),
      });
    }
    // Partial page means we're done — don't trust totalAvailable (ledger D-class).
    if (ds.length < pageSize) break;
    pageNumber++;
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/** True when a paginated request ran past the final page (pod-specific behavior). */
export function isPastEndError(e: unknown): boolean {
  return (
    e instanceof TableauError &&
    e.status === 400 &&
    /400006|greater than or equal to the total/i.test(e.bodySnippet)
  );
}

const LUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export function isLuidShape(value: string): boolean {
  return LUID_RE.test(value);
}

// -- VDS access ---------------------------------------------------------------

async function tryVdsReadMetadata(session: TableauSession, luid: string): Promise<VdsModel | null> {
  try {
    const data = await postJson<VdsReadMetadataResponse>(
      session,
      '/api/v1/vizql-data-service/read-metadata',
      { datasource: { datasourceLuid: luid } },
    );
    if (data && typeof data === 'object') return normalizeReadMetadataResponse(data);
  } catch (e) {
    if (e instanceof TableauError && e.kind === 'auth') throw e;
  }
  return null;
}

/** Convert the flat read-metadata envelope into the grouped model shape. */
function normalizeReadMetadataResponse(resp: VdsReadMetadataResponse): VdsModel {
  const rows = resp.data ?? [];

  // Newer surfaces may already return the grouped envelope — pass through.
  if (!Array.isArray(rows)) return {} as VdsModel;

  const groups = new Map<string, VdsField[]>();
  for (const row of rows) {
    // Pulse publish requires the RAW field name ("quantity"), not the human
    // caption ("Quantity") — captions are kept separately for display.
    const name = row.fieldName ?? row.fieldCaption;
    if (!name) continue;
    const tableId = row.logicalTableId ?? null;
    const field: VdsField = {
      name,
      caption: row.fieldCaption ?? row.fieldName,
      dataType: row.dataType,
      fieldType: row.fieldType,
      columnClass: row.columnClass,
      defaultAggregation: row.defaultAggregation ?? null,
      formula: row.formula ?? null,
      role: row.fieldRole === 'MEASURE' ? 'MEASURE' : 'DIMENSION',
      isHidden: row.isHidden === true,
      isInternal: row.isInternal === true,
      logicalTableId: tableId,
    };
    const key = tableId ?? '__calc__';
    const list = groups.get(key) ?? [];
    list.push(field);
    groups.set(key, list);
  }

  const fieldGroups = [...groups.entries()].map(([tableId, fields]) => ({
    logicalTableId: tableId === '__calc__' ? null : tableId,
    fields,
  }));

  // read-metadata doesn't include a logical-tables list; synthesize one from
  // the ids we saw so display captions can be derived.
  const logicalTableIds = new Set(
    rows.map((r) => r.logicalTableId).filter((id): id is string => Boolean(id)),
  );

  const parameters = (resp.extraData?.parameters ?? []).map((p) => ({
    name: p.parameterCaption ?? p.parameterName ?? '',
    parameterType: p.parameterType ?? '',
    dataType: p.dataType ?? '',
  }));

  return {
    datasourceModel: { logicalTables: [...logicalTableIds].map((logicalTableId) => ({ logicalTableId })) },
    fieldGroups,
    parameters,
    fieldProvenance: 'vds_read_metadata',
  };
}

/** Derive a display caption from a logical table id like `Orders_ECFCA1FB...`. */
function tableCaption(logicalTableId: string): string {
  const m = logicalTableId.match(/^(.*)_[0-9A-Fa-f]{8,}$/);
  return m ? m[1] : logicalTableId;
}

async function tryVdsDescribeDatasource(session: TableauSession, luid: string): Promise<VdsModel | null> {
  // Shape B seen across pods: describe-datasource with flat body
  try {
    const data = await postJson<VdsModel>(session, '/api/v1/vizql-data-service/describe-datasource', {
      datasourceLuid: luid,
    });
    if (data && typeof data === 'object') return normalizeVdsEnvelope(data);
  } catch (e) {
    if (e instanceof TableauError && e.kind === 'auth') throw e;
  }
  return null;
}

function normalizeVdsEnvelope(data: unknown): VdsModel {
  const d = data as any;
  // Some envelopes nest the model under datasource_model/model keys
  if (d?.datasourceModel || d?.fieldGroups || d?.parameters) {
    return { ...(d as VdsModel), fieldProvenance: 'vds_describe_datasource' };
  }
  if (d?.model) return { ...(d.model as VdsModel), fieldProvenance: 'vds_describe_datasource' };
  return {} as VdsModel;
}

function vdsLooksPopulated(model: VdsModel): boolean {
  return Array.isArray(model.fieldGroups) && model.fieldGroups.some((g) => (g.fields?.length ?? 0) > 0);
}

// -- normalization ------------------------------------------------------------

interface Classified extends CatalogField { }

function classifyField(
  raw: VdsField,
  tableName: string | null,
  logicalTableId: string | null,
  nameCounts: Map<string, number>,
  provenance: FieldProvenance,
): Classified | null {
  const name = raw.name?.trim();
  if (!name) return null;

  const formula = raw.formula ?? null;

  // A source that classifies fields itself (the Metadata API fallback) supplies
  // an explicit hint: null = allowed, a reason = excluded. `undefined` means
  // classify natively from VDS-provided fields.
  let exclusion: CatalogField['exclusion'];
  if (raw.exclusionHint !== undefined) {
    exclusion = raw.exclusionHint ?? undefined;
  } else {
    const columnClass = (raw.columnClass ?? '').toUpperCase();
    // VDS marks a calc TABLE_CALCULATION even when it only *references* a table
    // calc, so this alone covers the nested case — no formula scanning needed.
    if (columnClass === 'TABLE_CALCULATION') exclusion = 'table_calc';
    else if (columnClass === 'BIN') exclusion = 'bin';
    // `Calculation_*` is Tableau's raw name for both user-visible calculated
    // fields and internally generated fields. Only explicit metadata proves a
    // field is hidden or internal; `columnClass: CALCULATION` stays eligible.
    else if (raw.isHidden === true || raw.isInternal === true) exclusion = 'internal';
  }

  // A pre-aggregated field arrives with an aggregation and Pulse must publish it
  // with AGGREGATION_USER. VDS reports this via defaultAggregation: AGG (a
  // formula-level aggregate) or USER. A bare aggregation (SUM/YEAR/…) means VDS
  // aggregates it for us, so we own the aggregation as a Pulse metric.
  const requiresUserAgg =
    raw.requiresUserAggHint ??
    (!exclusion &&
      ((raw.defaultAggregation ?? '').toUpperCase() === 'AGG' ||
        (raw.defaultAggregation ?? '').toUpperCase() === 'USER'));

  const role: CatalogField['role'] = raw.role === 'MEASURE' ? 'MEASURE' : 'DIMENSION';
  // Tableau's `fieldType` describes field semantics such as NOMINAL,
  // ORDINAL, and CONTINUOUS. It is not a provider data type.
  const providerType = raw.dataType ?? raw.physicalType ?? null;
  const physicalType = raw.physicalType ?? null;
  const timeType = classifyNormalizedTimeType(raw.dataType, raw.physicalType);
  const dataType = timeType ?? normalizeProviderType(providerType) ?? 'STRING';

  const count = (nameCounts.get(name) ?? 0) + 1;
  nameCounts.set(name, count);
  // Display label prefers the human caption; `name`/`id` stay the raw field
  // name that Pulse publish + VDS queries require.
  const display = raw.caption?.trim() || name;
  const label = count > 1 ? `${display} (${tableName ?? 'calc'})` : display;

  return {
    id: name,
    name,
    label,
    caption: display,
    role,
    dataType,
    ...(timeType ? { timeType } : {}),
    providerType,
    physicalType,
    table: tableName,
    logicalTableId: raw.logicalTableId ?? logicalTableId,
    provenance: raw.provenance ?? provenance,
    defaultAggregation: raw.defaultAggregation ?? null,
    formula,
    requiresUserAgg,
    exclusion,
  };
}

export function normalizeVdsToCatalog(
  model: VdsModel,
  ds: RawDatasource,
  source: 'vds' | 'metadata',
  provenance: FieldProvenance = source === 'metadata'
    ? 'metadata_graphql'
    : (model.fieldProvenance ?? 'vds_describe_datasource'),
): DatasourceCatalog {
  const tablesById = new Map<string, string>();
  for (const t of model.datasourceModel?.logicalTables ?? []) {
    tablesById.set(t.logicalTableId, t.caption ?? tableCaption(t.logicalTableId));
  }

  const measures: CatalogField[] = [];
  const dimensions: CatalogField[] = [];
  const timeDimensions: CatalogField[] = [];
  const excluded: DatasourceCatalog['excluded'] = [];
  const warnings: string[] = [];
  const nameCounts = new Map<string, number>();
  const diagnostics: FieldCatalogDiagnostics = {
    counts: { discovered: 0, measures: 0, dimensions: 0, timeDimensions: 0, excluded: 0 },
    excludedByReason: {},
    timeDimensionExcludedByReason: { excluded: 0, measureRole: 0, unsupportedType: 0 },
    suspiciousZeroTimeDimensions: false,
  };

  for (const group of model.fieldGroups ?? []) {
    const tableName = group.logicalTableId ? (tablesById.get(group.logicalTableId) ?? null) : null;
    for (const raw of group.fields ?? []) {
      const field = classifyField(raw, tableName, group.logicalTableId ?? null, nameCounts, provenance);
      if (!field) continue;
      diagnostics.counts.discovered++;

      if (field.exclusion) {
        excluded.push({ field, reason: field.exclusion });
        diagnostics.counts.excluded++;
        diagnostics.excludedByReason[field.exclusion] = (diagnostics.excludedByReason[field.exclusion] ?? 0) + 1;
        diagnostics.timeDimensionExcludedByReason.excluded++;
        continue;
      }
      if (field.role === 'MEASURE') {
        measures.push(field);
        diagnostics.counts.measures++;
        diagnostics.timeDimensionExcludedByReason.measureRole++;
      } else if (field.timeType) {
        timeDimensions.push(field);
        diagnostics.counts.timeDimensions++;
      } else {
        dimensions.push(field);
        diagnostics.counts.dimensions++;
        diagnostics.timeDimensionExcludedByReason.unsupportedType++;
      }
    }
  }

  if (timeDimensions.length === 0) {
    diagnostics.suspiciousZeroTimeDimensions = true;
    warnings.push('No date/time dimensions found - Pulse metrics require a time dimension.');
  }
  if (measures.length === 0) {
    warnings.push('No usable measures found in this datasource.');
  }

  return {
    datasourceLuid: ds.luid,
    datasourceName: ds.name,
    measures: sortFields(measures),
    dimensions: sortFields(dimensions),
    timeDimensions: sortFields(timeDimensions),
    parameters: (model.parameters ?? [])
      .filter((p) => p.name)
      .map((p) => ({ name: p.name!, parameterType: p.parameterType ?? '', dataType: p.dataType ?? '' })),
    excluded,
    diagnostics,
    source,
    warnings,
  };
}

export function fieldCatalogCacheTtlMs(catalog: Pick<DatasourceCatalog, 'timeDimensions'>): number {
  return catalog.timeDimensions.length === 0 ? SUSPICIOUS_ZERO_TIME_CACHE_TTL_MS : CACHE_TTL_MS;
}

/**
 * The published-on-published (sqlproxy) edge case: VDS returns a calc's caption
 * as its internal `Calculation_NNN` id, so the builder has nothing human to
 * display. Detect those, and if any exist repair them from the Metadata API's
 * friendly names. Best-effort — never throws (aside from auth), never touches
 * id/name (Pulse resolves refs by the raw id, never the caption).
 */
const CALC_ID_RE = /^Calculation_\d+$/i;

async function enrichCalcCaptions(
  session: TableauSession,
  luid: string,
  catalog: DatasourceCatalog,
): Promise<void> {
  const buckets = [catalog.measures, catalog.dimensions, catalog.timeDimensions];
  const needsCaption = (field: CatalogField): boolean =>
    field.caption === field.name && CALC_ID_RE.test(field.name);
  const anyUnresolved =
    buckets.some((bucket) => bucket.some(needsCaption)) ||
    catalog.excluded.some((entry) => needsCaption(entry.field));
  if (!anyUnresolved) return;

  const captions = await fetchCaptionMap(session, luid);
  if (captions.size === 0) return;

  const repair = (field: CatalogField): void => {
    if (!needsCaption(field)) return;
    const friendly = captions.get(field.name);
    if (!friendly) return;
    // Preserve any dedup suffix the builder added: `Label (Table)` vs `Label`.
    const wasDeduped = field.label !== field.caption;
    field.caption = friendly;
    field.label = wasDeduped ? `${friendly} (${field.table ?? 'calc'})` : friendly;
  };
  for (const bucket of buckets) for (const field of bucket) repair(field);
  for (const entry of catalog.excluded) repair(entry.field);
}

function sortFields(fields: CatalogField[]): CatalogField[] {
  return [...fields].sort((a, b) => {
    const t = (a.table ?? '').localeCompare(b.table ?? '');
    return t !== 0 ? t : a.label.localeCompare(b.label);
  });
}

// -- public entrypoint --------------------------------------------------------

export async function getFieldCatalog(session: TableauSession, luid: string): Promise<DatasourceCatalog> {
  const cacheKey = fieldCatalogCacheKey(session, luid);
  const cached = cache.get(cacheKey);
  if (cached && Date.now() - cached.fetchedAt < fieldCatalogCacheTtlMs(cached.catalog)) {
    return { ...cached.catalog, source: 'cache' };
  }

  let dsName = luid;
  try {
    const all = await listDatasources(session);
    dsName = all.find((d) => d.luid === luid)?.name ?? luid;
  } catch {
    // listing failure shouldn't block field loading; name falls back to luid
  }

  let model = await tryVdsReadMetadata(session, luid);
  if (!model || !vdsLooksPopulated(model)) {
    model = await tryVdsDescribeDatasource(session, luid);
  }
  if (!model || !vdsLooksPopulated(model)) {
    const graphqlCatalog = await fetchFieldsViaMetadataGraphql(session, luid, { luid, name: dsName });
    cache.set(cacheKey, { catalog: graphqlCatalog, fetchedAt: Date.now() });
    return graphqlCatalog;
  }

  const catalog = normalizeVdsToCatalog(model, { luid, name: dsName }, 'vds');
  // Repair calc captions VDS could only give as `Calculation_NNN` (sqlproxy).
  try {
    await enrichCalcCaptions(session, luid, catalog);
  } catch (e) {
    if (e instanceof TableauError && e.kind === 'auth') throw e;
    // Enrichment is best-effort; a Metadata API failure leaves the raw ids.
  }
  cache.set(cacheKey, { catalog, fetchedAt: Date.now() });
  return catalog;
}
